// Run after bun run build: preserves card state and focus across the responsive breakpoint.
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
import { existsSync, readdirSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { serveDist } from './serve-dist.mjs'

const cache = join(homedir(), '.cache/ms-playwright')
const executablePath = process.env.CHROMIUM_PATH ?? readdirSync(cache).filter(name => name.startsWith('chromium-')).sort().reverse().map(name => join(cache, name, 'chrome-linux64/chrome')).find(existsSync)
if (!executablePath) throw new Error('Set CHROMIUM_PATH to a Chromium executable')
const browser = await chromium.launch({ executablePath })
try {
  for (const theme of /** @type {const} */ (['light', 'dark'])) {
    const context = await browser.newContext({ viewport: { width: 390, height: 600 }, locale: 'en-US', colorScheme: theme, deviceScaleFactor: 2 })
    await serveDist(context, 'dist')
    const page = await context.newPage()
    await page.goto('http://site.test/?q=U%2B5B57')
    const tile = page.locator('main .ui-tile').filter({ hasText: '字' }).first()
    await tile.waitFor()
    await tile.focus()
    await page.keyboard.press('Enter')
    const dialog = page.locator('dialog:modal')
    const card = page.locator('aside.card')
    const filter = card.locator('input[type="search"]')
    await filter.waitFor()
    await filter.fill('北京')
    const branch = card.locator('details').first()
    await branch.locator('summary').first().click()
    assert.equal(await branch.evaluate(el => el.hasAttribute('open')), false)
    const expanded = card.locator('details[open]').first()
    await expanded.waitFor({ state: 'attached' })
    await card.evaluate(el => { el.scrollTop = 250; Reflect.set(el, 'testMarker', {}) })
    const identity = await card.evaluateHandle(el => Reflect.get(el, 'testMarker'))
    assert.equal(await card.evaluate(el => el.scrollTop), 250)
    await page.setViewportSize({ width: 1100, height: 600 })
    await page.waitForFunction(() => !document.querySelector('dialog:modal') && document.querySelector('aside.card')?.parentElement?.classList.contains('shell'))
    await page.waitForFunction(() => document.querySelector('aside.card')?.scrollTop === 250)
    assert.equal(await filter.inputValue(), '北京')
    assert.equal(await branch.evaluate(el => el.hasAttribute('open')), false, 'manual disclosure state survives resizing')
    assert.equal(await expanded.evaluate(el => el.hasAttribute('open')), true)
    assert.equal(await card.evaluate((el, marker) => Reflect.get(el, 'testMarker') === marker, identity), true, 'card DOM survives resizing')
    assert.equal(await tile.evaluate(el => el === document.activeElement), true, 'closing the modal restores the invoker')
    await page.setViewportSize({ width: 390, height: 600 })
    assert.equal(await page.locator('dialog:modal').count(), 0, 'outside focus does not open the sheet on resize')
    await tile.click()
    await dialog.waitFor()
    assert.equal(await filter.inputValue(), '北京')
    assert.equal(await branch.evaluate(el => el.hasAttribute('open')), false)
    assert.ok(Math.abs(await card.evaluate(el => el.scrollTop) - 250) <= 50, 'reopening retains the scroll position')
    await page.setViewportSize({ width: 1100, height: 600 })
    await page.waitForFunction(() => document.querySelector('aside.card')?.parentElement?.classList.contains('shell'))

    await filter.focus()
    await card.evaluate(el => { el.scrollTop = 250 })
    await page.setViewportSize({ width: 390, height: 600 })
    await dialog.waitFor()
    assert.equal(await filter.evaluate(el => el === document.activeElement), true, 'focused desktop card stays focused in modal')
    assert.equal(await filter.inputValue(), '北京')
    assert.equal(await branch.evaluate(el => el.hasAttribute('open')), false, 'manual disclosure state survives resizing')
    assert.equal(await expanded.evaluate(el => el.hasAttribute('open')), true)
    assert.ok(Math.abs(await card.evaluate(el => el.scrollTop) - 250) <= 50, 'resizing retains the scroll position through reflow')

    const back = dialog.getByRole('button', { name: 'Back' })
    const status = dialog.locator('[role="status"]')
    const backBefore = await back.boundingBox()
    const contentBefore = await card.locator('article').boundingBox()
    await status.evaluate(el => { el.textContent = 'A long message '.repeat(8); el.classList.add('show') })
    await page.waitForFunction(() => {
      const sheet = document.querySelector('dialog:modal .card')
      const status = sheet?.querySelector('.sheet-status')
      return !!sheet && !!status && status.getBoundingClientRect().height > 40 && parseFloat(getComputedStyle(sheet).paddingBottom) >= status.getBoundingClientRect().height - 1
    })
    assert.deepEqual(await back.boundingBox(), backBefore, 'wrapped feedback does not move Back')
    assert.deepEqual(await card.locator('article').boundingBox(), contentBefore, 'wrapped feedback does not move card content')
    assert.match(await status.evaluate(el => getComputedStyle(el).fontFamily), /CDP Composition.*CNS Composed.*Han Ext/)
    const loaded = await page.evaluate(async () => (await document.fonts.load('16px "CDP Composition"', '\uF6A3')).length)
    assert.ok(loaded > 0, 'composition font is available to the status')
    await page.screenshot({ path: `/tmp/han-resize-fixed-${theme}.png` })
    await status.evaluate(el => { el.textContent = ''; el.classList.remove('show') })
    await page.waitForFunction(() => {
      const el = document.querySelector('dialog:modal .sheet-status')
      return !!el && el.getBoundingClientRect().height === 0
    })
    assert.deepEqual(await back.boundingBox(), backBefore, 'clearing feedback does not move Back')
    assert.deepEqual(await card.locator('article').boundingBox(), contentBefore, 'clearing feedback does not move content')
    await back.focus()
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'hidden' })
    await page.setViewportSize({ width: 1100, height: 600 })
    await page.waitForFunction(() => document.querySelector('aside.card')?.parentElement?.classList.contains('shell'))
    assert.equal(await card.evaluate(el => getComputedStyle(el).paddingBottom), '0px', 'mobile feedback spacing is removed on desktop')
    assert.equal(await filter.inputValue(), '北京')
    assert.equal(await branch.evaluate(el => el.hasAttribute('open')), false, 'manual disclosure state survives resizing')
    assert.equal(await expanded.evaluate(el => el.hasAttribute('open')), true)
    await page.setViewportSize({ width: 390, height: 600 })
    await page.goto('http://site.test/?set=ext_e_withdrawal_records')
    const proposal = page.locator('.records .ui-tile[title*="G_GJZ"]').first()
    await proposal.waitFor()
    await proposal.click()
    await dialog.waitFor()
    const record = card.locator('article')
    await record.evaluate(el => Reflect.set(el, 'testMarker', {}))
    const recordIdentity = await record.evaluateHandle(el => Reflect.get(el, 'testMarker'))
    await page.setViewportSize({ width: 1100, height: 600 })
    await page.waitForFunction(() => !document.querySelector('dialog:modal') && document.querySelector('aside.card')?.parentElement?.classList.contains('shell'))
    assert.equal(await record.evaluate((el, marker) => Reflect.get(el, 'testMarker') === marker, recordIdentity), true, 'proposal DOM survives resizing')
    await page.setViewportSize({ width: 390, height: 600 })
    await page.goto('http://site.test/?q=U%2BF6A3')
    const special = page.locator('main .ui-tile').filter({ hasText: '\uF6A3' }).first()
    await special.waitFor()
    await special.click()
    await dialog.waitFor()
    await dialog.getByRole('button', { name: 'Add to text' }).click()
    await status.getByText('Added \uF6A3', { exact: true }).waitFor()
    assert.match(await status.evaluate(el => getComputedStyle(el).fontFamily), /CDP Composition/)
    await page.screenshot({ path: `/tmp/han-special-feedback-${theme}.png` })
    await context.close()
    console.log(`ok ${theme}: card state, focus, feedback layout, and glyph font`)
  }
} finally { await browser.close() }
